def test_upgrade_database_disposes_the_engine(monkeypatch: pytest.MonkeyPatch) -> None:
    seen: list[str] = []

    def record(engine: Engine) -> None:
        seen.append(engine.url.render_as_string(hide_password=True))

    monkeypatch.setattr(migrate, "upgrade_schema", record)
    upgrade_database(_ENV)
    assert seen == ["postgresql+psycopg://eleicoes:***@127.0.0.1:25432/eleicoes"]


def test_upgrade_database_requires_the_settings() -> None:
    with pytest.raises(DatabaseConfigError):
        upgrade_database({})


