def _create_baseline(connection: Connection) -> None:
    for schema, table in sorted(BASELINE_TABLES):
        connection.execute(text(f"CREATE TABLE {schema}.{table} (id integer)"))


def _offline(revision: str) -> str:
    buffer = io.StringIO()
    config = migration_config()
    config.output_buffer = buffer
    command.upgrade(config, revision, sql=True)
    return buffer.getvalue()


def _offline_downgrade(revision: str) -> str:
    buffer = io.StringIO()
    config = migration_config()
    config.output_buffer = buffer
    command.downgrade(config, revision, sql=True)
    return buffer.getvalue()


class _PostgresDialect:
    name = "postgresql"


class _PostgresConnection:
    dialect = _PostgresDialect()

    def __init__(self) -> None:
        self.executed: list[tuple[object, object]] = []

    def execute(self, statement: object, params: object = None) -> None:
        self.executed.append((statement, params))


class _FakeEngine:
    def __init__(self, connection: _PostgresConnection) -> None:
        self._connection = connection

    @contextmanager
    def begin(self) -> Iterator[_PostgresConnection]:
        yield self._connection


